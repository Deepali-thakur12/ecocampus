CREATE TABLE students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(254) NOT NULL,
    department VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_students PRIMARY KEY (student_id),
    CONSTRAINT uq_students_email UNIQUE (email)
);

CREATE TABLE wallet_accounts (
    wallet_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_id NUMBER NOT NULL,
    balance NUMBER(12, 2) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_wallet_accounts PRIMARY KEY (wallet_id),
    CONSTRAINT uq_wallet_student UNIQUE (student_id),
    CONSTRAINT fk_wallet_student FOREIGN KEY (student_id)
        REFERENCES students (student_id),
    CONSTRAINT ck_wallet_balance_nonnegative CHECK (balance >= 0)
);

CREATE TABLE products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    product_name VARCHAR2(100) NOT NULL,
    category VARCHAR2(30) NOT NULL,
    unit_price NUMBER(10, 2) NOT NULL,
    stock_quantity NUMBER(10) DEFAULT 0 NOT NULL,
    is_refillable CHAR(1) DEFAULT 'N' NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT uq_products_name UNIQUE (product_name),
    CONSTRAINT ck_products_price_positive CHECK (unit_price > 0),
    CONSTRAINT ck_products_stock_nonnegative CHECK (stock_quantity >= 0),
    CONSTRAINT ck_products_refillable CHECK (is_refillable IN ('Y', 'N')),
    CONSTRAINT ck_products_active CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    product_name VARCHAR2(100) NOT NULL,
    unit_price NUMBER(10, 2) NOT NULL,
    quantity NUMBER(10) NOT NULL,
    subtotal NUMBER(12, 2) NOT NULL,
    discount_percent NUMBER(5, 2) DEFAULT 0 NOT NULL,
    discount_amount NUMBER(12, 2) DEFAULT 0 NOT NULL,
    total_amount NUMBER(12, 2) NOT NULL,
    reusable_container_used CHAR(1) DEFAULT 'N' NOT NULL,
    ordered_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_student FOREIGN KEY (student_id)
        REFERENCES students (student_id),
    CONSTRAINT fk_orders_product FOREIGN KEY (product_id)
        REFERENCES products (product_id),
    CONSTRAINT ck_orders_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_orders_amounts CHECK (
        subtotal >= 0
        AND discount_amount >= 0
        AND total_amount >= 0
        AND discount_amount <= subtotal
        AND total_amount = subtotal - discount_amount
    ),
    CONSTRAINT ck_orders_discount_percent CHECK (
        discount_percent >= 0 AND discount_percent <= 100
    ),
    CONSTRAINT ck_orders_reusable CHECK (reusable_container_used IN ('Y', 'N'))
);

CREATE TABLE fund_transfers (
    transfer_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    sender_wallet_id NUMBER NOT NULL,
    receiver_wallet_id NUMBER NOT NULL,
    amount NUMBER(12, 2) NOT NULL,
    transferred_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_fund_transfers PRIMARY KEY (transfer_id),
    CONSTRAINT fk_transfer_sender FOREIGN KEY (sender_wallet_id)
        REFERENCES wallet_accounts (wallet_id),
    CONSTRAINT fk_transfer_receiver FOREIGN KEY (receiver_wallet_id)
        REFERENCES wallet_accounts (wallet_id),
    CONSTRAINT ck_transfer_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfer_different_wallets CHECK (
        sender_wallet_id <> receiver_wallet_id
    )
);

CREATE TABLE balance_audit (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    wallet_id NUMBER NOT NULL,
    old_balance NUMBER(12, 2) NOT NULL,
    new_balance NUMBER(12, 2) NOT NULL,
    balance_change NUMBER(12, 2) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_balance_audit PRIMARY KEY (audit_id),
    CONSTRAINT fk_audit_wallet FOREIGN KEY (wallet_id)
        REFERENCES wallet_accounts (wallet_id)
);

CREATE TABLE sustainability_log (
    activity_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    order_id NUMBER NOT NULL,
    student_id NUMBER NOT NULL,
    activity_type VARCHAR2(30) NOT NULL,
    reusable_container_used CHAR(1) NOT NULL,
    containers_avoided NUMBER(10) DEFAULT 0 NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_sustainability_log PRIMARY KEY (activity_id),
    CONSTRAINT uq_sustainability_order UNIQUE (order_id),
    CONSTRAINT fk_sustainability_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT fk_sustainability_student FOREIGN KEY (student_id)
        REFERENCES students (student_id),
    CONSTRAINT ck_sustainability_reusable CHECK (
        reusable_container_used IN ('Y', 'N')
    ),
    CONSTRAINT ck_sustainability_avoided CHECK (containers_avoided >= 0)
);

CREATE INDEX ix_orders_student_date ON orders (student_id, ordered_at);
CREATE INDEX ix_products_stock_active ON products (is_active, stock_quantity);
CREATE INDEX ix_audit_wallet_date ON balance_audit (wallet_id, changed_at);

CREATE OR REPLACE TRIGGER trg_wallet_balance_audit
AFTER UPDATE OF balance ON wallet_accounts
FOR EACH ROW
WHEN (OLD.balance <> NEW.balance)
BEGIN
    INSERT INTO balance_audit (
        wallet_id,
        old_balance,
        new_balance,
        balance_change
    )
    VALUES (
        :NEW.wallet_id,
        :OLD.balance,
        :NEW.balance,
        :NEW.balance - :OLD.balance
    );
END;
